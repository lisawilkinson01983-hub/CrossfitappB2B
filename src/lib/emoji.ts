/** Flat lookup across every category, for a case-insensitive name search. */
export function searchEmoji(query: string): { char: string; name: string }[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const results: { char: string; name: string }[] = [];
  for (const category of EMOJI_CATEGORIES) {
    for (const emoji of category.emojis) {
      if (emoji.name.includes(q)) results.push(emoji);
    }
  }
  return results;
}
